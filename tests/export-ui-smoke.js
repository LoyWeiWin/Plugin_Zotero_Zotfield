async function runZotFieldsUISmoke(plugin, core) {
  await Zotero.uiReadyPromise;
  const win = Zotero.getMainWindow();
  const wait = ms => new Promise(resolve => win.setTimeout(resolve, ms));
  const checks = [];
  function check(value, label) { if (!value) throw Error(label); checks.push(label); }
  async function until(predicate, label) {
    for (let i = 0; i < 120; i++) { if (predicate()) return; await wait(50); }
    throw Error('Timed out: ' + label);
  }
  const collection = new Zotero.Collection();
  collection.name = 'Export parent collection';
  await collection.saveTx();
  const subcollection = new Zotero.Collection();
  subcollection.name = 'Export child collection';
  subcollection.parentID = collection.id;
  await subcollection.saveTx();
  const a = new Zotero.Item('journalArticle');
  a.setField('title', 'Robot, "intention" study');
  a.setCreators([{firstName:'Wei Win',lastName:'Loy',creatorType:'author'}]);
  a.setField('date', '2026-11-13');
  a.setField('DOI', '10.1234/test.1');
  a.setField('publicationTitle', 'Robotics Journal');
  a.setField('abstractNote', 'A study of shared robotic work.');
  a.setTags([{tag:'manual tag',type:0},{tag:'imported tag',type:1}]);
  a.setCollections([collection.id]);
  a.setField('extra', 'Original metadata: keep this');
  await a.saveTx();
  const b = new Zotero.Item('book');
  b.setField('title', '第二篇 — Research book');
  b.setField('date', '2025');
  b.setField('publisher', 'Test publisher');
  b.setCollections([subcollection.id]);
  await b.saveTx();
  const note = new Zotero.Item('note');
  note.parentID = a.id;
  note.setNote('<p>Important child note.</p>');
  await note.saveTx();
  const attachment = await Zotero.Attachments.linkFromURL({url:'https://example.test/paper.pdf',title:'Linked PDF',parentItemID:a.id});
  const discarded = new Zotero.Item('journalArticle');
  discarded.setField('title', 'Trashed reference');
  discarded.deleted = true;
  await discarded.saveTx();
  const schema = core.defaults();
  schema[0].aliases = {old:'reading'};
  schema[2].aliases = {legacy:'interview'};
  schema.push({id:'evidence',label:'Evidence notes',type:'text',column:false});
  await plugin.setSchema(schema);
  await plugin.enqueue(a, schema[0], 'old');
  await plugin.enqueue(a, schema[1], false);
  await plugin.enqueue(a, schema[2], ['legacy','interview','observation']);
  await plugin.enqueue(a, schema[3], 'Two lines\nwith commas, "quotes" and café');
  const originalExtra = a.getField('extra');
  await Zotero.Translators.getAllForType('export');
  const native = new Zotero.Translate.Export();
  native.setItems([a,b]);
  native.setTranslator(ZFExporter.csvTranslatorID);
  native.setDisplayOptions({exportNotes:true,exportFileData:false,exportCharset:'UTF-8'});
  await native.translate();
  const nativeRows = ZFCSV.parse(native.string);
  const output = await ZFExporter.buildCSV([a,b],schema,{includeNotes:true});
  const rows = ZFCSV.parse(output.csv), header = rows[0];
  const rowA = rows.find(row=>row[0]===a.key), rowB = rows.find(row=>row[0]===b.key);
  const get = (row,label) => row[header.indexOf(label)];
  check(nativeRows[0].length > 50, 'Uses the actual standard Zotero CSV translator');
  check(header.length === nativeRows[0].length + schema.length, 'Appends all custom research fields to the complete native CSV columns');
  check(JSON.stringify(header.slice(0,nativeRows[0].length)) === JSON.stringify(nativeRows[0]), 'Native column names and order match Zotero CSV');
  check(nativeRows.slice(1).every(row=>JSON.stringify(rows.find(v=>v[0]===row[0]).slice(0,row.length))===JSON.stringify(row)), 'All native field values match a direct Zotero CSV export');
  check(get(rowA,'Title') === 'Robot, "intention" study' && get(rowA,'Author') === 'Loy, Wei Win', 'Exports the built-in title and author with CSV quoting');
  check(get(rowA,'Publication Year') === '2026' && get(rowA,'DOI') === '10.1234/test.1', 'Exports publication year and DOI alongside custom fields');
  check(get(rowA,'Publication Title') === 'Robotics Journal' && get(rowA,'Abstract Note').includes('shared robotic'), 'Exports journal and abstract fields');
  check(get(rowA,'Manual Tags') === 'manual tag' && get(rowA,'Automatic Tags') === 'imported tag', 'Retains Zotero manual and automatic tag columns');
  check(get(rowA,'Link Attachments').includes('https://example.test/paper.pdf'), 'Retains linked attachment metadata without copying attachments');
  check(get(rowA,'Notes').includes('Important child note'), 'Can include child notes through the native exporter');
  check(get(rowA,'ZotFields: Read status') === 'Reading', 'Exports readable labels for merged choice values');
  check(get(rowA,'ZotFields: Foundational paper') === 'No', 'Exports false booleans distinctly from unset values');
  check(get(rowA,'ZotFields: Methods') === 'Interviews; Observation', 'Resolves and deduplicates merged multi-select options');
  check(get(rowA,'ZotFields: Evidence notes') === 'Two lines\nwith commas, "quotes" and café', 'Exports hidden custom fields, Unicode and multiline values');
  check(schema.every(field=>get(rowB,'ZotFields: '+field.label)===''), 'Leaves unset metadata blank on another reference');
  check(get(rowB,'Title') === '第二篇 — Research book' && get(rowB,'Publisher') === 'Test publisher', 'Exports item-type-specific native fields and Unicode');
  check(a.getField('extra') === originalExtra, 'Export does not modify stored research values or Extra text');
  const withoutNotes = ZFCSV.parse((await ZFExporter.buildCSV([a],schema)).csv);
  check(withoutNotes[1][withoutNotes[0].indexOf('Notes')] === '', 'Child notes are excluded unless requested');
  const context = {selected:[a,a,note,attachment,discarded],collectionID:collection.id,collectionName:collection.name,libraryID:a.libraryID,libraryName:Zotero.Libraries.getName(a.libraryID)};
  check((await ZFExporter.items(context,'selected')).length === 1, 'Selected export omits notes, attachments, duplicate selections and trash');
  check((await ZFExporter.items(context,'collection',false)).length === 1, 'Collection export can exclude subcollections');
  check((await ZFExporter.items(context,'collection',true)).length === 2, 'Collection export can include subcollections');
  check((await ZFExporter.items(context,'library')).length === 2, 'Library export includes active references and excludes trash');
  await win.ZoteroPane.collectionsView.selectByID('C'+collection.id);
  await win.ZoteroPane.selectItem(a.id);
  await wait(150);
  check(win.document.getElementById('zotfields-export') && win.document.getElementById('zotfields-export-items'), 'Registers export commands in Tools and the item context menu');
  const snapshot = ZFExporter.context(win);
  check(snapshot.selected.length === 1 && snapshot.collectionID === collection.id && snapshot.libraryID === a.libraryID, 'Captures the selected references, collection and library');
  win.document.getElementById('zotfields-export').dispatchEvent(new win.Event('command'));
  let dialog;
  await until(()=>{
    dialog=[...plugin.exportWindows].find(window=>!window.closed && window.document.getElementById('save-csv'));
    return dialog && dialog.document.getElementById('scope-selected').textContent.includes('(1)');
  },'Export dialog initialization');
  check(dialog.document.getElementById('scope').value === 'selected', 'The export dialog defaults to selected references');
  const { FilePicker } = ChromeUtils.importESModule('chrome://zotero/content/modules/filePicker.mjs');
  const nativePicker = new FilePicker();
  nativePicker.init(dialog, 'Export Zotero data and research metadata', nativePicker.modeSave);
  nativePicker.defaultString = 'ZotFields-export.csv';
  nativePicker.defaultExtension = 'csv';
  nativePicker.appendFilter('CSV', '*.csv');
  checks.push('Initializes the native CSV save picker in Gecko');
  const target=Zotero.DataDirectory.dir+'/zotfields-export-test.csv';
  const pick=ZFExporter.pickFile;
  ZFExporter.pickFile=async()=>target;
  async function submit() {
    const document=dialog.document;
    document.getElementById('export-form').dispatchEvent(new dialog.Event('submit',{bubbles:true,cancelable:true}));
    await until(()=>!document.getElementById('save-csv').disabled && !document.getElementById('status').textContent.startsWith('Preparing'), 'Export finishes');
    return document.getElementById('status').textContent;
  }
  const status=await submit();
  check(status.startsWith('Exported 1 reference with 4 research fields.'), 'The export form completes a combined CSV save');
  const saved=await Zotero.File.getContentsAsync(target);
  check(ZFCSV.parse(saved).length === 2 && ZFCSV.parse(saved)[0].includes('ZotFields: Read status'), 'Writes built-in and research metadata together in one CSV file');
  const d=dialog.document;
  d.getElementById('scope').value='collection';
  d.getElementById('scope').dispatchEvent(new dialog.Event('change'));
  check(!d.getElementById('recursive-label').hidden, 'Collection scope exposes the subcollection option');
  const collectionStatus=await submit();
  check(collectionStatus.startsWith('Exported 2 references'), 'The dialog exports a collection and its subcollection');
  const beforeCancel=await Zotero.File.getContentsAsync(target);
  ZFExporter.pickFile=async()=>null;
  check(await submit() === 'Export cancelled.', 'Cancelling the save dialog reports cancellation');
  check(await Zotero.File.getContentsAsync(target) === beforeCancel, 'Cancelling leaves an existing CSV untouched');
  ZFExporter.pickFile=async()=>target;
  d.getElementById('scope').value='selected';
  a.setField('extra','ZotFields: {broken');
  await a.saveTx();
  const failedStatus=await submit();
  check(failedStatus.startsWith('Export failed: Cannot export research metadata for'), 'Malformed metadata produces a visible export error');
  check(await Zotero.File.getContentsAsync(target) === beforeCancel, 'An export error does not overwrite an existing CSV');
  a.setField('extra',originalExtra); await a.saveTx();
  ZFExporter.pickFile=pick;
  await plugin.stop();
  await until(()=>dialog.closed,'Export window closes on disable');
  check(!win.document.getElementById('zotfields-export') && !win.document.getElementById('zotfields-export-items') && plugin.exportPopupListeners.size===0, 'Disabling removes export windows, menus and popup listeners');
  return {passed:checks.length,checks,version:Zotero.version,platform:'Linux x86_64 headless',nativeColumnCount:nativeRows[0].length,customColumnCount:schema.length};
}
